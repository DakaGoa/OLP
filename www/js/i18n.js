let lang = 'en';
try { lang = localStorage.getItem('olp.lang') || 'en'; } catch (_) { /* ignore */ }
if (!LANGS.includes(lang)) lang = 'en';

export function getLang() { return lang; }
export function setLang(next) {
  lang = LANGS.includes(next) ? next : 'en';
  try { localStorage.setItem('olp.lang', lang); } catch (_) { /* ignore */ }
  try { document.documentElement.lang = lang === 'sr' ? 'sr' : 'en'; } catch (_) { /* ignore */ }
}
setLang(lang);

export function t(key, vars) {
  const table = DICT[lang] || DICT.en;
  let str = table[key];
  if (str === undefined) str = DICT.en[key];
  if (str === undefined) return key;
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined || vars[k] === null ? '' : String(vars[k])));
}

/* Bilingual content fields: title / titleSr, description / descriptionSr, … */
export function localized(obj, field) {
  if (!obj) return '';
  if (lang === 'sr' && obj[field + 'Sr']) return obj[field + 'Sr'];
  return obj[field] || '';
}

export function categoryLabel(id) { return (CATEGORY_LABELS[lang] || CATEGORY_LABELS.en)[id] || CATEGORY_LABELS.en.special || 'Special'; }
export function dayNames() { return DAY_NAMES[lang] || DAY_NAMES.en; }
export function monthNames() { return MONTH_NAMES[lang] || MONTH_NAMES.en; }

